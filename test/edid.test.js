import assert from 'node:assert/strict'
import edid from '../src/lib/edid.js'

const CONNECTORS = ['dvid', 'hdmi14', 'hdmi20', 'dp11', 'dp12']

// build a connector map where only the listed connectors are supported
const only = (...supported) =>
  Object.fromEntries(CONNECTORS.map(c => [c, supported.includes(c)]))

const ALL = CONNECTORS
const NONE = []

// calculate with positional args matching the constructor
const calc = (hPx, vPx, refresh, margins, redBlnk, redBlnkV) =>
  new edid(hPx, vPx, refresh, margins, redBlnk, redBlnkV).calcEdid()

// compare the timing fields of a result against an expected subset
const assertTimings = (result, expected) => {
  const actual = Object.fromEntries(Object.keys(expected).map(k => [k, result[k]]))
  assert.deepEqual(actual, expected)
}

describe('Constructor', () => {
  it('sets params', () => {
    assert.deepEqual(new edid(1920, 1080, 60, false, true, 2).params, {
      hPx: 1920, vPx: 1080, refresh: 60, margins: false, redBlnk: true, redBlnkV: 2,
    })
  })

  it('defaults to 1920x1080@60, no margins, reduced blanking v2', () => {
    assert.deepEqual(new edid().params, {
      hPx: 1920, vPx: 1080, refresh: 60, margins: false, redBlnk: true, redBlnkV: 2,
    })
  })

  it('warning strings', () => {
    // check the defined warnings say the right thing, other tests then
    // refer to the defined warnings so there's only one place to update
    const { warnings } = new edid()

    assert.equal(warnings.hRounded, 'Horizontal pixel count rounded to nearest character cell')
    assert.equal(warnings.vRounded, 'Vertical pixel count rounded to nearest integer')
    assert.equal(warnings.aspect, 'Aspect ratio is not a CVT standard')
    assert.equal(warnings.refresh, 'Refresh rate is not a CVT standard')
    assert.equal(warnings.redBlnkRefresh, '60Hz recommended for reduced blanking v1')
    assert.equal(warnings.dp12, 'Only available as input on DP 1.2 connector & EDID must be generated by input source with EM ≥7.1')

    assert.equal(warnings.links.sl, 'Single Link Signal Bandwidth')
    assert.equal(warnings.links.dl, 'Dual Link Signal Bandwidth')
    assert.equal(warnings.links.gen1, 'Pixel Clock too high for all Gen 1 Cards')
    assert.equal(warnings.links.all, 'Pixel Clock too high for all cards')

    assert.equal(warnings.freq.above300, 'Above HDMI 1.4 & DP 1.1 spec')
    assert.equal(warnings.freq.above330, 'Above DVI, HDMI 1.4 and DP 1.1 spec')
    assert.equal(warnings.freq.dp12, 'DisplayPort 1.2 Only')
    assert.equal(warnings.freq.all, 'Not supported on any single connector')
  })
})

describe('Calculate EDID', () => {
  it('1920x1080@60 // no margins // no reduced blanking // v1', () => {
    const calcEdid = new edid(1920, 1080, 60, false, false, 1)
    const result = calcEdid.calcEdid()

    assertTimings(result, {
      links: 'DL',
      linksNote: calcEdid.warnings.links.dl,
      freq: '173.101',
      freqNote: '',

      hTotal: 2576,
      hFrontPorch: 128,
      hActive: 1920,
      hSync: 200,
      hPolarity: false,

      vTotal: 1120,
      vFrontPorch: 3,
      vActive: 1080,
      vSync: 5,
      vPolarity: true,
      vRate: 60,
    })
    assert.deepEqual(result.possConns, { input: only(...ALL), output: only(...ALL) })
    assert.deepEqual(result.warnings, [])
  })

  it('4096x2160@30 // margins // no reduced blanking // v2', () => {
    const calcEdid = new edid(4096, 2160, 30, true, false, 2)
    const result = calcEdid.calcEdid()

    assertTimings(result, {
      links: '4K',
      linksNote: calcEdid.warnings.links.gen1,
      freq: '389.019',
      freqNote: calcEdid.warnings.freq.above330,

      hTotal: 5696,
      hFrontPorch: 280,
      hActive: 4096,
      hSync: 448,
      hPolarity: false,

      vTotal: 2277,
      vFrontPorch: 3,
      vActive: 2160,
      vSync: 10,
      vPolarity: true,
      vRate: 30,
    })
    assert.deepEqual(result.possConns, {
      input: only('hdmi20', 'dp12'),
      output: only('hdmi20', 'dp12'),
    })
    assert.deepEqual(result.warnings, [calcEdid.warnings.aspect, calcEdid.warnings.refresh])
  })

  it('3840x2160@60 // margins // reduced blanking // v2', () => {
    const calcEdid = new edid(3840, 2160, 60, true, true, 2)
    const result = calcEdid.calcEdid()

    assertTimings(result, {
      links: '4K',
      linksNote: calcEdid.warnings.links.gen1,
      freq: '560.004',
      freqNote: calcEdid.warnings.freq.above330,

      hTotal: 4058,
      hFrontPorch: 8,
      hActive: 3840,
      hSync: 32,
      hPolarity: true,

      vTotal: 2300,
      vFrontPorch: 50,
      vActive: 2160,
      vSync: 8,
      vPolarity: false,
      vRate: 60,
    })
    assert.deepEqual(result.possConns, {
      input: only('hdmi20', 'dp12'),
      output: only('hdmi20', 'dp12'),
    })
    assert.deepEqual(result.warnings, [])
  })

  it('1920x1200@60 // no margins // reduced blanking // v1', () => {
    const result = calc(1920, 1200, 60, false, true, 1)

    assertTimings(result, {
      links: 'SL',
      freq: '154.128',
      hTotal: 2080,
      hFrontPorch: 48, // 160 blanking - 80 back porch - 32 sync
      hActive: 1920,
      hSync: 32,
      hPolarity: true,
      vTotal: 1235,
      vFrontPorch: 3,
      vActive: 1200,
      vSync: 6, // 16:10
      vPolarity: false,
    })
    assert.deepEqual(result.warnings, [])
  })

  it('no reduced blanking uses the standard 8px cell whichever version was last selected', () => {
    // the UI keeps the last reduced blanking version when it's turned off
    const afterV1 = calc(1923, 1080, 60, false, false, 1)
    const afterV2 = calc(1923, 1080, 60, false, false, 2)

    assert.deepEqual(afterV2, afterV1)
    assert.equal(afterV2.hActive, 1920)
    assert.equal(afterV2.hTotal % 8, 0)
  })

  it('reduced blanking v1 sets the V sync width from the aspect ratio', () => {
    assert.equal(calc(1024, 768, 60, false, true, 1).vSync, 4) // 4:3
    assert.equal(calc(1920, 1080, 60, false, true, 1).vSync, 5) // 16:9
    assert.equal(calc(1920, 1200, 60, false, true, 1).vSync, 6) // 16:10
    assert.equal(calc(1280, 1024, 60, false, true, 1).vSync, 7) // 5:4
    assert.equal(calc(2560, 2000, 60, false, true, 1).vSync, 10) // custom
  })

  it('reduced blanking v2 always uses an 8 line V sync', () => {
    assert.equal(calc(1024, 768, 60, false, true, 2).vSync, 8)
    assert.equal(calc(2560, 2000, 60, false, true, 2).vSync, 8)
  })

  it('accepts the string values the UI text inputs provide', () => {
    const fromNumbers = new edid().calcEdid({
      hPx: 2560, vPx: 2000, refresh: 60, margins: false, redBlnk: true, redBlnkV: 2,
    })
    const fromStrings = new edid().calcEdid({
      hPx: '2560', vPx: '2000', refresh: '60', margins: false, redBlnk: true, redBlnkV: 2,
    })

    assert.deepEqual({ ...fromStrings, vRate: 60 }, fromNumbers)
  })

  it('uses the params passed to calcEdid over the constructor values', () => {
    const calcEdid = new edid(1920, 1080, 60, false, true, 2)
    const result = calcEdid.calcEdid({
      hPx: 1280, vPx: 720, refresh: 50, margins: false, redBlnk: true, redBlnkV: 2,
    })

    assert.equal(result.hActive, 1280)
    assert.equal(result.vActive, 720)
    assert.equal(result.vRate, 50)
  })
})

// Published VESA CVT reduced blanking v2 timings, as an independent reference
describe('VESA CVT-RB v2 reference timings', () => {
  const vesa = [
    { format: [1920, 1080, 60], freq: '133.320', hTotal: 2000, vTotal: 1111, vFrontPorch: 17 },
    { format: [2560, 1440, 60], freq: '234.590', hTotal: 2640, vTotal: 1481, vFrontPorch: 27 },
    { format: [3840, 2160, 60], freq: '522.614', hTotal: 3920, vTotal: 2222, vFrontPorch: 48 },
  ]

  for (const { format: [h, v, hz], ...expected } of vesa) {
    it(`${h}x${v}@${hz}`, () => {
      assertTimings(calc(h, v, hz, false, true, 2), {
        ...expected,
        hFrontPorch: 8,
        hSync: 32,
        vSync: 8,
      })
    })
  }
})

describe('Warnings', () => {
  const { warnings } = new edid()

  it('none for a standard format', () => {
    assert.deepEqual(calc(1920, 1080, 60, false, true, 2).warnings, [])
  })

  it('horizontal pixels rounded to the v1 8px character cell', () => {
    const result = calc(1925, 1080, 60, false, true, 1)
    assert.equal(result.hActive, 1920)
    assert.deepEqual(result.warnings, [warnings.hRounded])
  })

  it('no horizontal rounding with the v2 1px character cell', () => {
    const result = calc(1925, 1080, 60, false, true, 2)
    assert.equal(result.hActive, 1925)
    assert.deepEqual(result.warnings, [])
  })

  it('vertical pixels rounded to an integer', () => {
    const result = calc(1920, 1080.5, 60, false, true, 2)
    assert.equal(result.vActive, 1080)
    assert.deepEqual(result.warnings, [warnings.vRounded])
  })

  it('custom aspect ratio without reduced blanking', () => {
    assert.deepEqual(calc(2560, 2000, 60, false, false, 1).warnings, [warnings.aspect])
  })

  it('custom aspect ratio with reduced blanking v1', () => {
    assert.deepEqual(calc(2560, 2000, 60, false, true, 1).warnings, [warnings.aspect])
  })

  it('no aspect warning when v1 rounding brings it back to a standard ratio', () => {
    assert.deepEqual(calc(1925, 1080, 60, false, true, 1).warnings, [warnings.hRounded])
  })

  it('non-standard refresh rate without reduced blanking', () => {
    assert.deepEqual(calc(1920, 1080, 59.94, false, false, 2).warnings, [warnings.refresh])
  })

  it('any refresh rate is fine with reduced blanking v2', () => {
    assert.deepEqual(calc(1920, 1080, 59.94, false, true, 2).warnings, [])
  })

  it('reduced blanking v1 recommends 60Hz', () => {
    assert.deepEqual(calc(1920, 1080, 50, false, true, 1).warnings, [warnings.redBlnkRefresh])
  })

  it('reduced blanking v1 at a non-standard rate gets both refresh warnings', () => {
    assert.deepEqual(calc(1920, 1080, 59.94, false, true, 1).warnings, [
      warnings.refresh,
      warnings.redBlnkRefresh,
    ])
  })

  it('over 4096 wide is DP 1.2 input only', () => {
    const result = calc(5120, 1440, 60, false, true, 2)
    assert.equal(result.links, 'Over 4K')
    assert.deepEqual(result.possConns.input, only('dp12'))
    assert.deepEqual(result.warnings, [warnings.dp12])
  })

  it('no DP 1.2 warning once the pixel clock is above 660MHz', () => {
    const result = calc(5120, 2880, 60, false, true, 2)
    assert(Number(result.freq) > 660)
    assert(!result.warnings.includes(warnings.dp12))
  })
})

describe('Link Capacity', () => {
  const { calcLinks } = new edid()
  const cases = {
    SL: [[1920, 133.320], [2048, 141.852], [1920, 165.000]],
    DL: [[2560, 251.289], [1280, 250.000], [1280, 165.001], [2560, 164.000],
      [2560, 330.000], [4096, 200.000], [4096, 330.000]],
    '4K': [[2560, 400.000], [2560, 330.001], [2560, 660.000], [4096, 500.000]],
    'Over 4K': [[2560, 661.000], [4097, 500.000]],
  }

  for (const [links, inputs] of Object.entries(cases)) {
    for (const [hPx, freq] of inputs) {
      it(`${hPx}px @ ${freq}MHz => ${links}`, () => {
        assert.equal(calcLinks(hPx, freq), links)
      })
    }
  }
})

describe('Aspect Ratio', () => {
  const { aspectRatio } = new edid()
  const cases = [
    [1024, 768, '4:3'],
    [1920, 1080, '16:9'],
    [3840, 2160, '16:9'],
    [1920, 1200, '16:10'],
    [1280, 1024, '5:4'],
    [1500, 900, '15:9'],
    [2560, 2000, 'custom'],
    [1920, 1081, 'custom'],
  ]

  for (const [h, v, aspect] of cases) {
    it(`${h}x${v} => ${aspect}`, () => {
      assert.equal(aspectRatio(h, v), aspect)
    })
  }
})

describe('Possible Connections', () => {
  const { possConns } = new edid()
  const cases = [
    { hPx: 1920, hTotal: 2576, freq: 180, input: ALL, output: ALL },
    { hPx: 4096, hTotal: 4176, freq: 300, input: ['hdmi20', 'dp12'], output: ['hdmi20', 'dp12'] },
    { hPx: 4088, hTotal: 4168, freq: 305, input: ['dvid', 'hdmi20', 'dp12'], output: ['dvid', 'hdmi20', 'dp12'] },
    // 4095 isn't a multiple of 8 so can't be an output
    { hPx: 4095, hTotal: 4175, freq: 300, input: ['dvid', 'hdmi14', 'hdmi20', 'dp12'], output: NONE },
    // 3996 is a multiple of 4 (DP 1.1) but not 8
    { hPx: 3996, hTotal: 4076, freq: 300, input: ALL, output: ['dp11'] },
    // HDMI 2.0 output must be under 600MHz, input can be up to 600MHz
    { hPx: 2560, hTotal: 2640, freq: 600, input: ['hdmi20', 'dp12'], output: ['dp12'] },
    { hPx: 2560, hTotal: 2640, freq: 661, input: NONE, output: NONE },
    // EM 7.1 wide inputs: DP 1.2 input supports over 4096 wide
    { hPx: 4097, hTotal: 4177, freq: 100, input: ['dp12'], output: NONE },
  ]

  for (const { hPx, hTotal, freq, input, output } of cases) {
    it(`${hPx}px (${hTotal} total) @ ${freq}MHz`, () => {
      assert.deepEqual(possConns(hPx, hTotal, freq), {
        input: only(...input),
        output: only(...output),
      })
    })
  }
})

describe('Links Note', () => {
  const e = new edid()
  const cases = [
    [[100, 164, 165], e.warnings.links.sl],
    [[165.001, 200, 330], e.warnings.links.dl],
    [[331, 400, 660], e.warnings.links.gen1],
    [[661, 1000], e.warnings.links.all],
  ]

  for (const [freqs, note] of cases) {
    it(note, () => {
      for (const freq of freqs) assert.equal(e.linksNote(freq), note, `${freq}MHz`)
    })
  }

  it('agrees with calcLinks at the 165MHz single link limit', () => {
    assert.equal(e.calcLinks(1920, 165), 'SL')
    assert.equal(e.linksNote(165), e.warnings.links.sl)
    assert.equal(e.calcLinks(1920, 165.001), 'DL')
    assert.equal(e.linksNote(165.001), e.warnings.links.dl)
  })

  it('works with the rounded string frequency calcEdid passes in', () => {
    assert.equal(e.linksNote('660.000'), e.warnings.links.gen1)
    assert.equal(e.linksNote('660.001'), e.warnings.links.all)
  })
})

describe('Frequency Note', () => {
  const e = new edid()
  const cases = [
    [[150, 300], ''],
    [[301, 315, 330], e.warnings.freq.above300],
    [[331, 450, 600], e.warnings.freq.above330],
    [[601, 630, 660], e.warnings.freq.dp12],
    [[661, 1000], e.warnings.freq.all],
  ]

  for (const [freqs, note] of cases) {
    it(note || 'No note', () => {
      for (const freq of freqs) assert.equal(e.freqNote(freq), note, `${freq}MHz`)
    })
  }

  it('works with the rounded string frequency calcEdid passes in', () => {
    assert.equal(e.freqNote('300.000'), '')
    assert.equal(e.freqNote('300.001'), e.warnings.freq.above300)
  })
})
